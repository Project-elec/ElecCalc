/**
 * คืนค่า { tableId, cols } สำหรับอ่านพิกัดกระแสจาก WIRE_TABLES
 * หรือ null ถ้าไม่มีข้อมูลรองรับ (เช่น กลุ่มที่ 4 ไม่มีสายหลายแกน)
 *
 * count คือจำนวนตัวนำกระแส (2 หรือ 3) ใช้กับกลุ่มที่ตารางต้นฉบับแยกคอลัมน์ตามจำนวนนี้จริง
 * (กลุ่มที่ 1, 2 จากตารางที่ 5-20); กลุ่มอื่นที่ตารางไม่ได้แยก (เช่น กลุ่มที่ 5/6 ที่ใช้ป้าย
 * "แกนเดี่ยว/หลายแกน" รวมกัน) จะได้คอลัมน์เดิมไม่ว่าจะเลือกค่าใด
 *
 * กลุ่มที่ 3 (ตารางที่ 5-21) ใช้เฉพาะคอลัมน์ "พีวีซี 70°C" (คอลัมน์ 1/3) เท่านั้น เพราะคอลัมน์
 * "ครอสลิงค์พอลิเอทิลีน 90°C" (คอลัมน์ 2/4) รับรองเฉพาะสาย IEC 60502-1 ไม่ใช่สาย NYY
 *
 * arrangement ใช้เฉพาะกลุ่มที่ 4 (ตารางที่ 5-22 สายแกนเดี่ยวบนลูกถ้วย) เลือกรูปแบบการวางสาย
 * เป็น 'vertical' (แนวดิ่งขนานผนัง, คอลัมน์ 0) หรือ 'horizontal' (แนวนอนตั้งฉากออกจากผนัง, คอลัมน์ 1)
 * ค่าเริ่มต้นคือ vertical
 *
 * trayArrangementCol ใช้เฉพาะกลุ่มที่ 7 (ตารางที่ 5-30/5-31 บนรางเคเบิล) ระบุ "ดัชนีคอลัมน์" ของ
 * รูปแบบการวางสายที่เลือกจาก TRAY_ARRANGEMENTS[trayType] (กรองตาม coreType ก่อนแล้ว) ถ้าไม่ระบุ
 * (undefined/null) จะ fallback ไปใช้ค่าพิกัดกระแส "ต่ำสุด" ของทุกรูปแบบที่ตรงกับ coreType นั้นไว้ก่อน
 * เพื่อความปลอดภัย (conservative) เหมือนพฤติกรรมเดิมก่อนมีตัวเลือกนี้
 */
function getWireColumnSpec(group, count, coreType, trayType, arrangement = 'vertical', trayArrangementCol) {
  const isSingle = coreType === 'single';

  switch (group) {
    case 1: {
      const base = count === 3 ? 2 : 0;
      return { tableId: 'table-5-20', cols: [base + (isSingle ? 0 : 1)] };
    }
    case 2: {
      const base = count === 3 ? 6 : 4;
      return { tableId: 'table-5-20', cols: [base + (isSingle ? 0 : 1)] };
    }
    case 3:
      return { tableId: 'table-5-21', cols: isSingle ? [1] : [3] };
    case 4:
      return isSingle ? { tableId: 'table-5-22', cols: [arrangement === 'horizontal' ? 1 : 0] } : null;
    case 5:
      return { tableId: 'table-5-23', cols: count === 3 ? [1] : [0] };
    case 6:
      return { tableId: 'table-5-23', cols: [2] };
    case 7: {
      const tableId = trayType || 'table-5-30';
      const options = (TRAY_ARRANGEMENTS[tableId] || []).filter((a) => a.coreType === coreType);
      if (!options.length) return null;
      const selected = options.find((a) => a.col === trayArrangementCol);
      return { tableId, cols: selected ? [selected.col] : options.map((a) => a.col) };
    }
    default:
      return null;
  }
}
