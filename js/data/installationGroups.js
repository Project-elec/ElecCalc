// กลุ่มที่มีแถวหัวตาราง "จำนวนตัวนำกระแส" (2/3 เส้น) จริงในตารางต้นฉบับ
// กลุ่มที่ 4 และ 7 ไม่มีแถวนี้ (แยกด้วยรูปแบบการติดตั้ง/ลักษณะตัวนำเท่านั้น) จึงไม่ต้องแสดงตัวเลือกนี้
const GROUPS_WITH_CONDUCTOR_COUNT = [1, 2, 3, 5, 6];

/**
 * คืนค่า { tableId, cols } สำหรับอ่านพิกัดกระแสจาก WIRE_TABLES
 * หรือ null ถ้าไม่มีข้อมูลรองรับ (เช่น กลุ่มที่ 4 ไม่มีสายหลายแกน)
 *
 * count คือจำนวนตัวนำกระแส (2 หรือ 3) ใช้กับกลุ่มที่ตารางต้นฉบับแยกคอลัมน์ตามจำนวนนี้จริง
 * (กลุ่มที่ 1, 2 จากตารางที่ 5-20); กลุ่มอื่นที่ตารางไม่ได้แยก (เช่น กลุ่มที่ 3 ใช้ช่วง "ไม่เกิน 3"
 * ร่วมกัน หรือกลุ่มที่ 5/6 ที่ใช้ป้าย "แกนเดี่ยว/หลายแกน" รวมกัน) จะได้คอลัมน์เดิมไม่ว่าจะเลือกค่าใด
 */
function getWireColumnSpec(group, count, coreType, trayType) {
  const isSingle = coreType === 'single';

  switch (group) {
    case 1: {
      const base = count === 3 ? 2 : 0;
      return { tableId: 'table-5-20', cols: [base + (isSingle ? 0 : 1)] };
    }
    case 2: {
      const base = count === 3 ? 6 : 4;
      return { tableId: 'table-5-20', cols: [base + (isSingle ? 0 : 1)] };
    }
    case 3:
      return { tableId: 'table-5-21', cols: isSingle ? [1] : [3] };
    case 4:
      return isSingle ? { tableId: 'table-5-22', cols: [0] } : null;
    case 5:
      return { tableId: 'table-5-23', cols: count === 3 ? [1] : [0] };
    case 6:
      return { tableId: 'table-5-23', cols: [2] };
    case 7: {
      const tableId = trayType || 'table-5-30';
      if (tableId === 'table-5-30') {
        return { tableId, cols: isSingle ? [0, 1, 2, 3] : [4] };
      }
      return { tableId, cols: isSingle ? [0, 1] : [2, 3] };
    }
    default:
      return null;
  }
}
